def get_validated_lang(lang_code):
    """
    전달받은 언어 코드가 유효한지 검증하고, 유효하지 않은 경우 기본값('kor')을 반환합니다.
    """
    if not lang_code or lang_code.lower() not in SUPPORTED_LANGUAGES:
        return DEFAULT_LANGUAGE
    return lang_code.lower()

