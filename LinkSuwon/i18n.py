def translate(lang_code, key):
    """
    주어진 언어 코드와 키에 해당하는 번역 텍스트를 반환합니다.
    존재하지 않거나 지원하지 않는 경우 한국어 텍스트를 반환합니다.
    """
    valid_lang = get_validated_lang(lang_code)
    lang_dict = I18N_DICTS.get(valid_lang, I18N_DICTS[DEFAULT_LANGUAGE])
    return lang_dict.get(key, I18N_DICTS[DEFAULT_LANGUAGE].get(key, ''))
